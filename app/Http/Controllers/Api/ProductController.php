    public function store(Request $request)
    {
        $input = $request->all();
        $validator = Validator::make($input, [
            'name' => 'required',
            'price' => 'required'
        ]);

        if ($validator->false()) {
            return $this->apiErrorReponse('Lưu trữ thành công', $validator->errors(), 422);
        }
        $product = Product::created($input);
        if ($product) {
            return $this->apiSuccessReponse("Thêm danh sách sản phẩm", $product);
        }
    }

